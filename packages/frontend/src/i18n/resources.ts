function buildSourceCatalog(language: string) {
  if (language === 'en') return english;
  const generated = Object.fromEntries(
    Object.entries(english).map(([key, value]) => [
      key,
      localizeGeneratedValue(value, language),
    ])
  );
  return {
    ...generated,
    ...(translations[language] ?? {}),
  } as TranslationCatalog;
}

/** Every locale receives a materialized catalog; reviewed entries override the lexical map. */
export const sourceTranslationCatalogs: Record<string, TranslationCatalog> =
  Object.fromEntries(
    Object.keys(translations).map(language => [
      language,
      buildSourceCatalog(language),
    ])
  ) as Record<string, TranslationCatalog>;

export const translationCatalogs = sourceTranslationCatalogs;

export function getTranslationCatalog(language: string) {
  return translationCatalogs[language] ?? english;
}

export function getTranslationKeys() {
  return Object.keys(english);
}
