const generatedPhrases: Record<
  string,
  Record<string, string>
> = Object.fromEntries(
  generatedPhraseLanguages.map((language, languageIndex) => [
    language,
    Object.fromEntries(
      generatedPhraseRows.map(([source, targets]) => [
        source,
        targets[languageIndex],
      ])
    ),
  ])
) as Record<string, Record<string, string>>;

function escapeRegExp(value: string) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

type GeneratedLocalizationMatcher = {
  pattern: RegExp;
  replacements: Map<string, string>;
};

const generatedLocalizationMatchers = new Map<
  string,
  GeneratedLocalizationMatcher | null
>();

function getGeneratedLocalizationMatcher(language: string) {
  if (generatedLocalizationMatchers.has(language)) {
    return generatedLocalizationMatchers.get(language) ?? null;
  }

  const terms = generatedTerms[language];
  if (!terms) {
    generatedLocalizationMatchers.set(language, null);
    return null;
  }

  const entries = Object.entries({
    ...(generatedPhrases[language] ?? {}),
    ...terms,
  }).sort(([left], [right]) => right.length - left.length);
  if (entries.length === 0) {
    generatedLocalizationMatchers.set(language, null);
    return null;
  }

  // Replace against the original text in one pass. A sequential reducer can
  // re-match English words inside a translated value (for example French
  // `Assistant IA` becoming `assistant IA IA`) and produce mixed-language copy.
  const sourcePattern = (source: string) =>
    `${/\w/u.test(source) ? '\\b' : ''}${escapeRegExp(source)}${/\w$/u.test(source) ? '\\b' : ''}`;
  const matcher = {
    pattern: new RegExp(
      `(?:${entries.map(([source]) => sourcePattern(source)).join('|')})`,
      'gu'
    ),
    replacements: new Map(entries),
  } satisfies GeneratedLocalizationMatcher;
  generatedLocalizationMatchers.set(language, matcher);
  return matcher;
}

function localizeGeneratedValue(value: string, language: string) {
  const matcher = getGeneratedLocalizationMatcher(language);
  if (!matcher) return value;
  return value.replace(
    matcher.pattern,
    match => matcher.replacements.get(match) ?? match
  );
}

