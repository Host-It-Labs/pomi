import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { performance } from 'node:perf_hooks';
import { spawnSync } from 'node:child_process';

const root = path.resolve(import.meta.dirname, '..');
const dryRun = process.argv.includes('--dry-run');
const outputArgument = process.argv.find(argument =>
  argument.startsWith('--output-dir=')
);
const outputDirectory = path.resolve(
  root,
  outputArgument?.slice('--output-dir='.length) ?? 'docs/testing/results'
);
const defaultOutputDirectory = path.join(root, 'docs/testing/results');
const modes = [
  { name: 'parallel', runs: 10, workers: 7, fullyParallel: true },
  { name: 'serial', runs: 3, workers: 1, fullyParallel: false },
];

function percentile(values, percentileValue) {
  const ordered = [...values].sort((left, right) => left - right);
  const rank = (ordered.length - 1) * percentileValue;
  const lower = Math.floor(rank);
  const upper = Math.ceil(rank);
  if (lower === upper) return ordered[lower];
  return Math.round(
    ordered[lower] + (ordered[upper] - ordered[lower]) * (rank - lower)
  );
}

function summarize(results, expectedRuns) {
  const successful = results.filter(result => result.exitCode === 0);
  const durations = successful.map(result => result.durationMs);
  return {
    status: successful.length === expectedRuns ? 'complete' : 'incomplete',
    expectedRuns,
    successfulRuns: successful.length,
    p50Ms: durations.length > 0 ? percentile(durations, 0.5) : null,
    p95Ms: durations.length > 0 ? percentile(durations, 0.95) : null,
    minMs: durations.length > 0 ? Math.min(...durations) : null,
    maxMs: durations.length > 0 ? Math.max(...durations) : null,
    results,
  };
}

function formatDuration(durationMs) {
  if (durationMs === null) return 'pending';
  return `${(durationMs / 1000).toFixed(2)} s`;
}

function writeReport(modeResults) {
  const report = {
    schemaVersion: 1,
    generatedBy: 'pnpm test:e2e:timing',
    percentileMethod: 'linear interpolation over successful full-suite runs',
    retries: 0,
    journeyCount: 13,
    modes: Object.fromEntries(
      modes.map(mode => [
        mode.name,
        {
          workers: mode.workers,
          fullyParallel: mode.fullyParallel,
          ...summarize(modeResults[mode.name], mode.runs),
        },
      ])
    ),
  };
  const markdown = `# E2E timing summary

Generated by \`pnpm test:e2e:timing\`. Durations measure one complete 13-journey wrapper run, including deterministic cleanup and fixture provisioning. Percentiles use linear interpolation over successful runs. Failed or missing runs keep the mode incomplete.

| Mode | Workers | Required runs | Successful | p50 | p95 | Min | Max | Status |
| --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |
${modes
  .map(mode => {
    const summary = report.modes[mode.name];
    return `| ${mode.name} | ${mode.workers} | ${summary.expectedRuns} | ${summary.successfulRuns} | ${formatDuration(summary.p50Ms)} | ${formatDuration(summary.p95Ms)} | ${formatDuration(summary.minMs)} | ${formatDuration(summary.maxMs)} | ${summary.status} |`;
  })
  .join('\n')}
`;

  mkdirSync(outputDirectory, { recursive: true });
  writeFileSync(
    path.join(outputDirectory, 'e2e-timing.json'),
    `${JSON.stringify(report, null, 2)}\n`
  );
  writeFileSync(path.join(outputDirectory, 'e2e-timing.md'), markdown);
}

if (dryRun) {
  process.stdout.write(
    `${JSON.stringify(
      {
        outputDirectory: path.relative(root, outputDirectory),
        modes,
        command: [
          './scripts/run-e2e.sh',
          'e2e/journeys.spec.ts',
          '--retries=0',
          '--timeout=45000',
        ],
      },
      null,
      2
    )}\n`
  );
  process.exit(0);
}

const modeResults = Object.fromEntries(modes.map(mode => [mode.name, []]));
let failed = false;

for (const mode of modes) {
  for (let index = 0; index < mode.runs; index += 1) {
    process.stderr.write(`E2E timing ${mode.name} ${index + 1}/${mode.runs}\n`);
    const startedAt = performance.now();
    const result = spawnSync(
      './scripts/run-e2e.sh',
      [
        'e2e/journeys.spec.ts',
        `--workers=${mode.workers}`,
        '--retries=0',
        '--timeout=45000',
      ],
      {
        cwd: root,
        env: {
          ...process.env,
          CI: '1',
          POMI_E2E_ADMIN_REPEAT_COUNT: '1',
          PLAYWRIGHT_CI_WORKERS: String(mode.workers),
          PLAYWRIGHT_FULLY_PARALLEL: mode.fullyParallel ? '1' : '0',
        },
        stdio: 'inherit',
      }
    );
    const durationMs = Math.round(performance.now() - startedAt);
    modeResults[mode.name].push({
      run: index + 1,
      durationMs,
      exitCode: result.status ?? 1,
    });
    writeReport(modeResults);

    if (result.status !== 0) {
      failed = true;
      break;
    }
  }
  if (failed) break;
}

if (failed) {
  process.exit(1);
}

const inventory = spawnSync(
  process.execPath,
  [
    './scripts/test-inventory.mjs',
    `--output-dir=${path.relative(root, outputDirectory)}`,
  ],
  { cwd: root, stdio: 'inherit' }
);
if (inventory.status !== 0) process.exit(inventory.status ?? 1);

if (outputDirectory === defaultOutputDirectory) {
  const ownership = spawnSync(
    process.execPath,
    ['./scripts/generate-e2e-ownership.mjs'],
    { cwd: root, stdio: 'inherit' }
  );
  process.exit(ownership.status ?? 1);
}
